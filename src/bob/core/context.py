import runpy
import sys
from pathlib import Path
from types import TracebackType
from typing import TYPE_CHECKING, Any, ClassVar

from typing_extensions import Self

from bob.constants import (
    BOB_BUILDDIR_SUBDIRECTORY,
    get_build_ninja_path,
    get_compdb_ninja_path,
    get_configs_path,
    get_used_configs_path,
)
from bob.external.ninja_syntax import Writer
from bob.external.ninja_syntax import escape as ninja_escape

if TYPE_CHECKING:
    from bob.api.scope import Scope


class Context:
    _current: ClassVar["None | Context"] = None

    def __init__(
        self,
        builddir: Path,
        bobfile: Path,
        configs: dict[str, str],
        allow_build_outside_builddir: bool,
    ):
        from bob.api.rule import FileTarget, PhonyTarget, RuleInput

        self.builddir = builddir
        self.bobfile = bobfile
        self.allow_build_outside_builddir = allow_build_outside_builddir
        self.configs = configs
        self.used_configs: set[str] = set()
        self.writer: None | Writer = None
        self.compdb_writer: None | Writer = None
        self.configure_implicit_dependencies: set[RuleInput.Type] = set()
        self.configure_phony_implicit_dependencies: set[RuleInput.Type] = {
            FileTarget(get_configs_path(builddir))
        }
        self.counters: dict[str, int] = {}
        # TODO: remove in 0.2. Bob no longer uses these, but plugins may still keep state in them.
        self.variables: dict[str, Any] = {}
        self.srcdir = Path(".")
        self.imports: None | dict[str, Any] = None
        self.exports: dict[str, Any] = {}
        self.always: PhonyTarget | None = None
        self.scopes: list[Scope] = []
        self.track_scopes = True

        self.current_build_subdir = Path(".")
        self.current_src_subdir = bobfile.parent

    def __enter__(self) -> "Self":
        assert Context._current is None

        (self.builddir / BOB_BUILDDIR_SUBDIRECTORY).mkdir(parents=True, exist_ok=True)

        self.writer = Writer(
            get_build_ninja_path(self.builddir).open("w"),
            width=999999,
        )
        self.compdb_writer = Writer(
            get_compdb_ninja_path(self.builddir).open("w"),
            width=999999,
        )

        self.writer.comment("This file was automatically generated by Bob.")
        self.writer.variable(
            "builddir", ninja_escape(str(self.builddir / BOB_BUILDDIR_SUBDIRECTORY))
        )

        Context._current = self

        from bob.api.rule import phony

        self.always = phony(str(self.builddir / BOB_BUILDDIR_SUBDIRECTORY / "always"))

        self.writer.newline()

        return self

    def __exit__(
        self,
        exc_type: None | type[BaseException],
        exc: None | BaseException,
        tb: None | TracebackType,
    ) -> None:
        succeeded = False
        try:
            if exc is None:
                self._write_configure_edge()
                get_used_configs_path(self.builddir).write_text(
                    "\n".join(sorted(self.used_configs))
                )
                succeeded = True
        finally:
            assert self.writer is not None
            assert self.compdb_writer is not None
            self.writer.close()
            self.writer = None
            self.compdb_writer.close()
            self.compdb_writer = None

            if not succeeded:
                get_build_ninja_path(self.builddir).unlink(missing_ok=True)
                get_compdb_ninja_path(self.builddir).unlink(missing_ok=True)

            assert Context._current is self
            Context._current = None

    def _write_configure_edge(self) -> None:
        from bob.api.rule import Rule, RuleInput

        # The recorded dependencies are already relative to the working directory, so resolve them
        # from the root rather than from whichever srcdir/builddir a Bobfile happened to leave active.
        self.current_src_subdir = Path(".")
        self.current_build_subdir = Path(".")

        def key(dependency: RuleInput.Type) -> str:
            return RuleInput.resolve(dependency, path_only=True, convert_to_string=True)

        assert self.writer is not None
        self.writer.build(
            sorted(
                key(dependency)
                for dependency in self.configure_phony_implicit_dependencies
            ),
            "phony",
        )

        Rule(
            "FORCE_COLOR=1 $bobbin configure --use-current-configs $bobargs",
            description="CONFIGURE",
            generator=True,
            pool="console",
        ).build(
            str(get_build_ninja_path(self.builddir).relative_to(self.builddir)),
            implicit=sorted(
                self.configure_implicit_dependencies
                | self.configure_phony_implicit_dependencies,
                key=key,
            ),
            variables={
                "bobbin": [sys.executable, "-m", "bob"],
                # Values are attached with `=` so that they can't be taken as options themselves.
                "bobargs": [
                    f"--builddir={self.builddir}",
                    f"--bobfile={self.bobfile}",
                    *(
                        ["--allow-build-outside-builddir"]
                        if self.allow_build_outside_builddir
                        else []
                    ),
                ],
            },
        )

    @staticmethod
    def current() -> "Context":
        result = Context._current
        assert result is not None
        return result

    def next_index(self, kind: str) -> int:
        """Return a 1-based index that is unique for `kind` within this configuration."""
        index = self.counters.get(kind, 0) + 1
        self.counters[kind] = index
        return index

    def evaluate(
        self,
        bobfile: Path,
        validate_configs: bool = True,
        restore_configs: bool = True,
    ) -> None:
        original_used_configs = self.used_configs

        if validate_configs:
            self.used_configs = set()

        self.configure_phony_implicit_dependencies.add(bobfile)

        runpy.run_path(str(bobfile))

        assert self.track_scopes, (
            "An unclosed plugin scope was detected, this can cause a myriad of side-effects!"
        )

        if validate_configs:
            for key in self.configs:
                assert key in self.used_configs, f'Invalid config "{key}"'
            if restore_configs:
                self.used_configs = original_used_configs
